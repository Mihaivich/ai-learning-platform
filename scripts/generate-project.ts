/*
 * Generates a project draft from the command line, for authors reviewing what
 * the AI writes before the in-app flow exists.
 *
 *   npm run generate:project -- "marketing" "a loyalty programme for a café" [out.json]
 *
 * Prints the checks and writes the draft as JSON (stdout when no file is given).
 */
import { writeFile } from "node:fs/promises";
import { generateProject } from "../src/lib/projects/generated/generate";

async function main() {
  const [domain, topic, out] = process.argv.slice(2);
  if (!domain || !topic) {
    console.error('Usage: npm run generate:project -- "<domain>" "<topic>" [out.json]');
    process.exitCode = 1;
    return;
  }
  const started = Date.now();
  const result = await generateProject({ domain, topic }, { id: "draft-preview" });
  const seconds = ((Date.now() - started) / 1000).toFixed(1);
  if ("error" in result) {
    console.error(`${result.error} (${seconds}s)`);
    for (const problem of result.check?.problems ?? []) console.error(`  problem: ${problem}`);
    process.exitCode = 1;
    return;
  }
  console.error(`Generated by ${result.model} in ${seconds}s, ${result.attempts} attempt(s).`);
  for (const warning of result.check.warnings) console.error(`  warning: ${warning}`);
  const json = JSON.stringify(result.draft, null, 2);
  if (out) {
    await writeFile(out, json + "\n");
    console.error(`Wrote ${out}`);
  } else {
    console.log(json);
  }
}

void main();
