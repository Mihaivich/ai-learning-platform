/*
 * Generates a project draft from the command line, for authors reviewing what
 * the AI writes before the in-app flow exists.
 *
 *   npm run generate:project -- "marketing" "a loyalty programme for a café" [out.json]
 *   npm run generate:project -- "healthcare" "infection rates on a ward" out.json \
 *     --subject "statistics" --learner "a second-year nursing student"
 *
 * Prints the checks and writes the draft as JSON (stdout when no file is given).
 */
import { writeFile } from "node:fs/promises";
import { generateProject } from "../src/lib/projects/generated/generate";
import { LEVELS } from "../src/lib/projects/generated/profile";

async function main() {
  const args = process.argv.slice(2);
  const option = (name: string) => {
    const at = args.indexOf(`--${name}`);
    if (at < 0) return undefined;
    const [, value] = args.splice(at, 2);
    return value;
  };
  const subject = option("subject");
  const learner = option("learner");
  const level = LEVELS.find((item) => item === option("level"));
  const [domain, topic, out] = args;
  if (!domain || (!topic && !subject)) {
    console.error('Usage: npm run generate:project -- "<domain>" "<topic>" [out.json] [--subject "<subject>"] [--learner "<who>"] [--level none|some|comfortable]');
    process.exitCode = 1;
    return;
  }
  const started = Date.now();
  const result = await generateProject({ domain, topic: topic ?? "", subject, learner, level }, { id: "draft-preview" });
  const seconds = ((Date.now() - started) / 1000).toFixed(1);
  if ("error" in result) {
    console.error(`${result.error} (${seconds}s)`);
    for (const problem of result.check?.problems ?? []) console.error(`  problem: ${problem}`);
    process.exitCode = 1;
    return;
  }
  console.error(`Generated by ${result.model} in ${seconds}s, ${result.attempts} attempt(s).`);
  for (const warning of result.check.warnings) console.error(`  warning: ${warning}`);
  const json = JSON.stringify(result.draft, null, 2);
  if (out) {
    await writeFile(out, json + "\n");
    console.error(`Wrote ${out}`);
  } else {
    console.log(json);
  }
}

void main();
